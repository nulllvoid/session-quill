// Export the existing Quill identity and token values; no runtime dependencies.
// node scripts/build-ui-assets.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { icon } from '../ui/components.js';
import { logoSvg } from '../ui/views/header.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const css = fs.readFileSync(path.join(root, 'ui/styles.css'), 'utf8');
const source = fs.readFileSync(path.join(root, 'ui/components.js'), 'utf8');
const outputs = new Map();
const put = (name, body) => outputs.set(`ui/assets/${name}`, body.trim() + '\n');
const declarations = (body) => Object.fromEntries([...body.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const dark = declarations(css.match(/:root\[data-theme="dark"\][^{]*\{([^}]+)\}/)[1]);
const roots = [...css.matchAll(/(?:^|\n):root \{([^}]+)\}/g)];
const light = declarations(roots[0][1]);
const shared = declarations(roots[1][1]);
const primitives = {
  'q-space-1': '4px', 'q-space-2': '8px', 'q-space-3': '12px', 'q-space-4': '16px',
  'q-space-5': '20px', 'q-space-6': '24px', 'q-space-8': '32px', 'q-space-12': '48px',
  'q-type-caption': '12px', 'q-type-small': '13px', 'q-type-body': '15px',
  'q-type-section': '18px', 'q-type-title': '25px',
  'q-radius-control': '6px', 'q-radius-card': '10px', 'q-radius-panel': '12px',
  'q-control-height': '36px', 'q-touch-target': '44px', 'q-motion-fast': '160ms',
  'q-motion-normal': '200ms', 'q-content-max': '1320px',
};
const rule = (selector, values) => `${selector} {\n${Object.entries(values).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}`;
put('tokens.css', `/* Generated by scripts/build-ui-assets.mjs. Existing theme values + additive q-* primitives.
   Opt-in reference stylesheet; not loaded by the production dashboard. */
@font-face { font-family: "Geist"; src: url("../fonts/Geist-Variable.woff2") format("woff2"); font-weight: 100 900; font-display: swap; }
@font-face { font-family: "Geist Mono"; src: url("../fonts/GeistMono-Variable.woff2") format("woff2"); font-weight: 100 900; font-display: swap; }
${rule(':root', { ...shared, ...primitives, ...light })}
:root { color-scheme: light; }
@media (prefers-color-scheme: dark) { ${rule(':root:not([data-theme="light"])', dark)} :root:not([data-theme="light"]) { color-scheme: dark; } }
${rule(':root[data-theme="dark"]', dark)}
:root[data-theme="dark"] { color-scheme: dark; }`);
put('tokens.json', JSON.stringify({ name: 'Quill Fieldnotes', version: '1.0.0', format: 'quill-css-token-map-v1', source: 'ui/styles.css', note: 'Theme/shared values mirror the app. q-* primitives are additive reference-kit values; this is not a DTCG-format file.', light, dark, shared, primitives }, null, 2));

const logo = logoSvg().replace('class="logo" ', '').replace('width="28" height="28"', 'width="32" height="32"');
for (const [name, fill, fg] of [['light', '#245c49', '#ffffff'], ['dark', '#91cebb', '#142e26']]) {
  put(`brand/quill-mark-${name}.svg`, logo.replaceAll('var(--accent-fill)', fill).replaceAll('var(--accent-fg)', fg).replace('aria-hidden="true"', 'role="img" aria-label="Session Quill"'));
}
put('brand/quill-mark-mono.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32" fill="currentColor" role="img" aria-label="Session Quill"><path d="M22.5 7.5c-6 1-10.5 5.5-12 13l-1 4 3.2-2.6c6.8-1.4 10.3-6.2 9.8-14.4Z"/></svg>');

const currentNames = [...source.slice(source.indexOf('const ICONS ='), source.indexOf('export function icon')).matchAll(/^  (\w+):/gm)].map((m) => m[1]);
const extensions = {
  runs: '<path d="M2 3h5M2 8h5M2 13h5M10 4l4 4-4 4Z"/>',
  queue: '<path d="M2 4h12M2 8h8M2 12h5"/><circle cx="12" cy="12" r="2"/>',
  approve: '<rect x="3" y="2" width="10" height="12" rx="2"/><path d="m5 8 2 2 4-4"/>',
  diff: '<path d="M2 2h12v12H2ZM8 2v12M4 5h2M10 10h2M11 9v2"/>',
  tests: '<path d="M5 2h6M6 2v4l-3 6a1.3 1.3 0 0 0 1 2h8a1.3 1.3 0 0 0 1-2l-3-6V2M5 10h6"/>',
  lock: '<rect x="3" y="7" width="10" height="7" rx="2"/><path d="M5 7V5a3 3 0 0 1 6 0v2M8 10v1"/>',
  expand: '<path d="M2 6V2h4M10 2h4v4M14 10v4h-4M6 14H2v-4"/>',
  collapse: '<path d="M6 2v4H2M14 6h-4V2M10 14v-4h4M2 10h4v4"/>',
};
const glyphs = Object.fromEntries(currentNames.map((name) => [name, icon(name).replace(/.*?<svg[^>]*>/, '').replace('</svg>', '')]));
Object.assign(glyphs, extensions);
for (const [name, body] of Object.entries(glyphs)) {
  put(`icons/${name}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`);
}
put('icons/sprite.svg', `<svg xmlns="http://www.w3.org/2000/svg"><defs>${Object.entries(glyphs).map(([name, body]) => `<symbol id="quill-${name}" viewBox="0 0 16 16"><g fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${body}</g></symbol>`).join('')}</defs></svg>`);

const illustrations = {
  'empty-queue': '<rect x="74" y="34" width="172" height="112" rx="12"/><path d="M96 61h70M96 79h128M96 97h99"/><path class="accent" d="m137 120 14 14 31-34"/>',
  'no-results': '<circle cx="140" cy="80" r="42"/><path d="m171 111 43 43M120 80h40"/><path class="accent" d="M91 37H65v27M214 103h26v-27"/>',
  'review-ready': '<rect x="96" y="23" width="128" height="140" rx="10"/><path d="M119 49h60M119 68h83M119 88h51"/><circle class="accent" cx="202" cy="130" r="28"/><path class="accent" d="m188 131 10 10 18-22"/>',
  'worker-offline': '<rect x="71" y="30" width="178" height="103" rx="10"/><path d="M137 155h46M160 133v22M120 78h21M179 78h21"/><path class="accent" d="m150 65 20 26M170 65l-20 26"/>',
};
for (const [name, body] of Object.entries(illustrations)) {
  for (const [suffix, ink, accent] of [['', '#627169', '#23634f'], ['-dark', '#9baaa3', '#91cebb']]) {
    const art = body.replaceAll('class="accent"', `stroke="var(--art-accent, ${accent})"`);
    put(`illustrations/${name}${suffix}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180" viewBox="0 0 320 180" fill="none" role="img" aria-label="${name.replaceAll('-', ' ')}"><g stroke="var(--art-ink, ${ink})" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${art}</g></svg>`);
  }
}
put('manifest.json', JSON.stringify({ name: 'Quill UI assets', version: '1.0.0', license: 'MIT; see ../../LICENSE. Existing fonts retain ui/fonts/OFL.txt.', generatedBy: 'scripts/build-ui-assets.mjs', files: [...outputs.keys()].map((name) => ({ path: name.replace('ui/assets/', ''), role: name.includes('/brand/') ? 'brand' : name.includes('/icons/') ? 'icon' : name.includes('/illustrations/') ? 'empty-state illustration' : 'tokens', provenance: name.includes('/icons/') && name !== 'ui/assets/icons/sprite.svg' ? currentNames.includes(path.basename(name, '.svg')) ? 'existing ui/components.js glyph' : 'new Quill orchestration extension; not integrated into icon()' : 'Quill repository design system' })) }, null, 2));

const stale = [];
for (const [name, text] of outputs) {
  const target = path.join(root, name);
  if (check) { if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) stale.push(name); }
  else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, text); }
}
if (stale.length) { console.error(`Outdated/missing assets:\n${stale.join('\n')}`); process.exitCode = 1; }
else console.log(`${check ? 'Verified' : 'Generated'} ${outputs.size} Quill assets.`);
