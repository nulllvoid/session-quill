const root = document.documentElement;
const themeButton = document.querySelector('#theme');
const notice = document.querySelector('#notice');
let timer;
function notify(text) { notice.textContent = text; notice.hidden = false; clearTimeout(timer); timer = setTimeout(() => { notice.hidden = true; }, 4200); }
function refreshSwatches() {
  const style = getComputedStyle(root);
  for (const tile of document.querySelectorAll('[data-token]')) tile.querySelector('code').textContent = style.getPropertyValue(`--${tile.dataset.token}`).trim();
}
themeButton.addEventListener('click', () => {
  const dark = root.dataset.theme !== 'dark'; root.dataset.theme = dark ? 'dark' : 'light';
  themeButton.setAttribute('aria-pressed', String(dark)); refreshSwatches();
  for (const art of document.querySelectorAll('.q-empty img')) { const name = art.getAttribute('src').replace('-dark.svg', '.svg'); art.src = dark ? name.replace('.svg', '-dark.svg') : name; }
  document.querySelector('.brand img').src = `../../ui/assets/brand/quill-mark-${dark ? 'dark' : 'light'}.svg`;
});
const palette = [['bg','Canvas'],['surface','Surface'],['accent-fill','Primary action'],['status-active','Running'],['status-review','Needs review'],['critical','Failure']];
document.querySelector('#swatches').innerHTML = palette.map(([token, label]) => `<div class="swatch" data-token="${token}"><div class="swatch-color" style="background:var(--${token})"></div><p>${label}</p><code></code></div>`).join('');
refreshSwatches();
document.querySelector('#spacing').innerHTML = [4,8,12,16,20,24,32,48].map((n)=>`<div style="height:${n}px"><span>${n}</span></div>`).join('');
async function loadIcons() {
  try {
    const response = await fetch('../../ui/assets/manifest.json'); if (!response.ok) throw new Error('Asset manifest unavailable');
    const manifest = await response.json();
    const icons = manifest.files.filter((f)=>f.role==='icon' && f.path!=='icons/sprite.svg');
    const grid = document.querySelector('#icons');
    for (const asset of icons) {
      const name = asset.path.split('/').pop().replace('.svg','');
      const button = document.createElement('button'); button.type='button'; button.className='icon-tile'; button.dataset.name=name; button.setAttribute('aria-label',`Copy ${name} SVG`);
      // Assets are local, repository-owned SVG, generated by build-ui-assets.mjs.
      const result = await fetch(`../../ui/assets/${asset.path}`); if (!result.ok) throw new Error(`Could not load ${name}`);
      const svg=await result.text(); button.innerHTML=svg;
      const label=document.createElement('span'); label.textContent=name; button.append(label);
      button.addEventListener('click',async()=>{ try { await navigator.clipboard.writeText(svg); notify(`Copied ${name}.svg`); } catch { notify(`Clipboard unavailable. Download ui/assets/${asset.path} from the asset folder.`); } });
      grid.append(button);
      filterIcons();
    }
  } catch (error) { document.querySelector('#icons').textContent=`${error.message}. Serve this reference from the repository root over localhost; file:// cannot load the SVG catalog.`; }
}
// Catalog fetches must not delay keyboard and demo controls.
loadIcons();
function filterIcons() { let count=0; const query=document.querySelector('#icon-search').value.trim().toLowerCase(); for(const tile of document.querySelectorAll('.icon-tile')) { tile.hidden=!tile.dataset.name.includes(query); if(!tile.hidden)count++; } document.querySelector('#icon-empty').hidden=count!==0; }
document.querySelector('#icon-search').addEventListener('input', filterIcons);
const tabs=[...document.querySelectorAll('.q-tab')];
function selectTab(tab,focus=false) { for(const item of tabs) { const active=item===tab; item.setAttribute('aria-selected',String(active));item.tabIndex=active?0:-1;document.querySelector(`#panel-${item.dataset.panel}`).hidden=!active; }if(focus)tab.focus(); }
for(const [index,tab] of tabs.entries()) { tab.addEventListener('click',()=>selectTab(tab));tab.addEventListener('keydown',(e)=>{if(!['ArrowLeft','ArrowRight','Home','End'].includes(e.key))return;e.preventDefault();const next=e.key==='Home'?0:e.key==='End'?tabs.length-1:(index+(e.key==='ArrowRight'?1:tabs.length-1))%tabs.length;selectTab(tabs[next],true);}); }
